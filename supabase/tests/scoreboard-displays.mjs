import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

// Run against an in-memory PostgreSQL instance; never uses the hosted project.
// Install @electric-sql/pglite in a temporary directory and set PGLITE_MODULE
// to its dist/index.js, or install it in this test environment's node_modules.
const { PGlite } = await import(process.env.PGLITE_MODULE ? pathToFileURL(process.env.PGLITE_MODULE).href : '@electric-sql/pglite');
const db = new PGlite();
const manager = '11111111-1111-4111-8111-111111111111';
const outsider = '22222222-2222-4222-8222-222222222222';
const competition = '33333333-3333-4333-8333-333333333333';
const division = '44444444-4444-4444-8444-444444444444';
const matchId = '55555555-5555-4555-8555-555555555555';
const scalar = async (sql, params = []) => (await db.query(sql, params)).rows[0]?.value;
const role = async (name, user = '') => { await db.exec(`set role ${name}`); await db.query("select set_config('request.jwt.claim.sub', $1, false)", [user]); };

try {
  // Minimal existing schema, preserving the field types and relationships used
  // by the new migration. The migration itself is loaded verbatim below.
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema auth to anon, authenticated;
    create table public.profiles(id uuid primary key, display_name text, email text);
    create table public.venues(id text primary key, name text);
    create table public.courts(id text primary key, venue_id text references venues, name text, active boolean default true);
    create table public.venue_members(venue_id text, user_id uuid, role text);
    create function public.can_manage_venue(target text) returns boolean language sql stable security definer set search_path = '' as $$ select exists(select 1 from public.venue_members where venue_id = target and user_id = auth.uid() and role in ('owner','manager')) $$;
    create function public.is_platform_admin() returns boolean language sql stable as $$ select false $$;
    create table public.teams(id uuid primary key, name text);
    create table public.open_play_sessions(id text primary key, venue_id text, name text, status text);
    create table public.open_play_courts(id text primary key, session_id text, venue_court_id text, court_number integer);
    create table public.open_play_players(id text primary key, user_id uuid, guest_name text);
    create table public.open_play_matches(id text primary key, session_id text, session_court_id text, status text, home_score integer, away_score integer, started_at timestamptz default now(), server_side smallint, service_number smallint);
    create table public.open_play_match_players(match_id text, player_id text, side smallint, position smallint);
    create table public.competitions(id uuid primary key, venue_id text, name text, kind text, status text);
    create table public.competition_divisions(id uuid primary key, competition_id uuid, name text, position integer default 1);
    create table public.competition_entries(id uuid primary key, competition_id uuid, competition_division_id uuid, user_id uuid, team_id uuid, status text, seed integer, played integer, won integer, lost integer, points_for integer, points_against integer, standing_points integer);
    create table public.matches(id uuid primary key, venue_id text, competition_id uuid, competition_division_id uuid, court_id text, status text, scheduled_at timestamptz, created_at timestamptz default now(), updated_at timestamptz, team_home_id uuid, team_away_id uuid, resume_state jsonb);
    create table public.match_games(match_id uuid, game_number integer, home_score integer, away_score integer);
    create table public.match_participants(match_id uuid, user_id uuid, guest_name text, side smallint, position smallint);
    create table public.competition_bracket_matches(id uuid primary key, competition_id uuid, competition_division_id uuid, round_number integer, position integer, status text, home_entry_id uuid, away_entry_id uuid, winner_entry_id uuid, match_id uuid);
  `);
  await db.exec(await readFile(new URL('../migrations/202609120001_court_scoreboard_displays.sql', import.meta.url), 'utf8'));
  await db.exec(`
    insert into profiles values ('${manager}', 'Alex Home', 'private@example.invalid'), ('${outsider}', 'Sam Away', 'private2@example.invalid');
    insert into venues values ('venue-a','Venue A'), ('venue-b','Venue B');
    insert into courts values ('court-1','venue-a','Court 1',true), ('court-2','venue-a','Court 2',true), ('other-court','venue-b','Private Court',true);
    insert into venue_members values ('venue-a','${manager}','owner'), ('venue-b','${outsider}','owner');
    insert into open_play_sessions values ('session-a','venue-a','Evening open play','active'), ('session-b','venue-b','Private session','active');
    insert into open_play_courts values ('session-court-1','session-a','court-1',1), ('session-court-2','session-a','court-2',2), ('other-session-court','session-b','other-court',1);
    insert into open_play_players values ('home','${manager}',null), ('away','${outsider}',null);
    insert into open_play_matches values ('live-1','session-a','session-court-1','live',7,4,now(),0,2), ('live-2','session-a','session-court-2','live',3,9,now(),1,1);
    insert into open_play_match_players values ('live-1','home',0,0), ('live-1','away',1,0), ('live-2','home',0,0), ('live-2','away',1,0);
    insert into competitions values ('${competition}','venue-a','Community Cup','tournament','active');
    insert into competition_divisions(id,competition_id,name) values ('${division}','${competition}','Open singles');
    insert into matches(id,venue_id,competition_id,competition_division_id,court_id,status,resume_state) values ('${matchId}','venue-a','${competition}','${division}',null,'live','{"scores":[8,6],"server":1,"serviceNumber":1,"privateNote":"do not expose","gameScores":[[11,5]],"paused":true}');
    insert into match_participants values ('${matchId}','${manager}',null,0,0), ('${matchId}','${outsider}',null,1,0);
    insert into match_games values ('${matchId}',1,11,5);
    insert into competition_entries values ('66666666-6666-4666-8666-666666666666','${competition}','${division}','${manager}',null,'active',1,2,2,0,22,12,6), ('77777777-7777-4777-8777-777777777777','${competition}','${division}','${outsider}',null,'active',2,2,1,1,18,16,3);
    insert into competition_bracket_matches values ('88888888-8888-4888-8888-888888888888','${competition}','${division}',1,1,'live','66666666-6666-4666-8666-666666666666','77777777-7777-4777-8777-777777777777',null,'${matchId}');
  `);
  const save = async (overrides = {}) => scalar(`select to_jsonb(public.save_venue_display($1,$2,$3,$4,$5,$6,$7,$8,$9)) as value`, Object.values({ id: null, venue: 'venue-a', name: 'Court 1 TV', kind: 'open_play', source: 'session-a', mode: 'court', court: 'session-court-1', division: null, revision: null, ...overrides }));
  const snapshot = (token) => scalar('select public.get_scoreboard_display($1) as value', [token]);
  const setup = (venue, kind, source) => scalar('select public.get_venue_display_setup($1,$2,$3) as value', [venue, kind, source]);

  await role('authenticated', manager);
  assert.equal((await setup('venue-a', 'open_play', 'session-a')).courts.length, 2);
  assert.equal((await setup('venue-a', 'competition', competition)).matches[0].label, 'Alex Home vs Sam Away');
  await assert.rejects(setup('venue-a', 'open_play', 'session-b'), /session at this venue/);
  const display1 = await save();
  const display2 = await save({ name: 'Court 2 TV', court: 'session-court-2' });
  assert.match(display1.token, /^[a-f0-9]{64}$/);
  assert.notEqual(display1.token, display2.token);
  await assert.rejects(save({ court: 'other-session-court' }), /Choose a court from this session/);
  await assert.rejects(save({ source: 'session-b' }), /Choose an open-play session at this venue/);
  await assert.rejects(save({ mode: 'standings', court: null }), /check constraint/);
  await role('authenticated', outsider);
  assert.equal((await db.query("select * from venue_displays where venue_id = 'venue-a'")).rows.length, 0);
  await assert.rejects(save(), /Venue manager access required/);
  await assert.rejects(setup('venue-a', 'competition', competition), /Venue manager access required/);
  await assert.rejects(db.query('select reset_venue_display_link($1,1,true)', [display1.id]), /Venue manager access required/);
  await assert.rejects(db.query('select delete_venue_display($1,1)', [display1.id]), /Venue manager access required/);
  await role('anon');
  await assert.rejects(db.query('select * from venue_displays'), /permission denied/);
  await assert.rejects(save(), /permission denied/);
  await assert.rejects(setup('venue-a', 'competition', competition), /permission denied/);
  await assert.rejects(db.query('select delete_venue_display($1,1)', [display1.id]), /permission denied/);
  await assert.rejects(db.query("update open_play_matches set home_score = 99"), /permission denied/);
  await assert.rejects(db.query('select app_private.scoreboard_competition_match($1)', [matchId]), /permission denied/);
  assert.deepEqual(await snapshot('bad-token'), { available: false });
  assert.deepEqual(await snapshot('a'.repeat(64)), { available: false });
  const first = await snapshot(display1.token);
  const second = await snapshot(display2.token);
  assert.equal(first.courts.length, 1);
  assert.equal(first.courts[0].name, 'Court 1');
  assert.equal(first.courts[0].match.home_score, 7);
  assert.equal(second.courts[0].name, 'Court 2');
  assert.equal(second.courts[0].match.home_score, 3);
  assert.ok(!JSON.stringify(first).includes('private@example'));
  assert.ok(!JSON.stringify(first).includes(display1.token));
  console.log('PASS anonymous read-only links and venue/court isolation');

  await role('authenticated', manager);
  const changed = await save({ id: display1.id, revision: 1, name: 'Reassigned TV', court: 'session-court-2' });
  await assert.rejects(save({ id: display1.id, revision: 1 }), /settings changed/);
  await role('anon');
  assert.equal((await snapshot(display1.token)).courts[0].id, 'session-court-2');
  assert.equal((await snapshot(display2.token)).display.name, 'Court 2 TV');
  await role('authenticated', manager);
  const rotated = await scalar('select to_jsonb(reset_venue_display_link($1,$2,false)) as value', [changed.id, changed.revision]);
  await role('anon');
  assert.deepEqual(await snapshot(display1.token), { available: false });
  assert.equal((await snapshot(rotated.token)).available, true);
  await role('authenticated', manager);
  await db.query('select reset_venue_display_link($1,$2,true)', [rotated.id, rotated.revision]);
  await role('anon');
  assert.deepEqual(await snapshot(rotated.token), { available: false });
  console.log('PASS remote reassignment, optimistic concurrency, rotation and disconnect');

  await role('postgres');
  await db.exec("update open_play_matches set status = 'completed' where id = 'live-2'");
  assert.equal((await snapshot(display2.token)).courts[0].match, null);
  await db.exec("insert into open_play_matches values ('next-match','session-a','session-court-2','live',1,0,now(),0,2)");
  assert.equal((await snapshot(display2.token)).courts[0].match.id, 'next-match');
  await db.exec("update open_play_sessions set status = 'completed' where id = 'session-a'");
  assert.equal((await snapshot(display2.token)).courts[0].match, null);
  console.log('PASS court display follows successive matches and clears ended events');

  await role('authenticated', manager);
  const compDisplay = await save({ kind: 'competition', source: competition, court: 'court-1' });
  await assert.rejects(save({ kind: 'competition', source: competition, court: 'other-court' }), /active court at this venue/);
  await assert.rejects(db.query('select assign_competition_display_court($1,$2,null)', [matchId, 'other-court']), /active court at this venue/);
  await assert.rejects(db.query('select assign_competition_display_court($1,$2,null)', [matchId, 'court-1']), /already has a live match/);
  await role('postgres');
  await db.exec("update open_play_matches set status = 'completed'");
  await role('authenticated', manager);
  await db.query('select assign_competition_display_court($1,$2,null)', [matchId, 'court-1']);
  await assert.rejects(db.query('select assign_competition_display_court($1,$2,null)', [matchId, 'court-2']), /assignment changed/);
  await role('anon');
  const live = (await snapshot(compDisplay.token)).courts[0].match;
  assert.equal(live.home_score, 8);
  assert.equal(live.away_score, 6);
  assert.equal(live.server_side, 1);
  assert.equal(live.game, 2);
  assert.equal(live.paused, true);
  assert.ok(!JSON.stringify(live).includes('privateNote'));
  await role('postgres');
  await db.exec(`update matches set status = 'completed' where id = '${matchId}'; insert into match_games values ('${matchId}',2,11,6)`);
  assert.equal((await snapshot(compDisplay.token)).courts[0].match, null);
  await role('authenticated', manager);
  const bracket = await save({ kind: 'competition', source: competition, mode: 'bracket', court: null, division });
  const standings = await save({ kind: 'competition', source: competition, mode: 'standings', court: null, division });
  await role('anon');
  assert.equal((await snapshot(bracket.token)).bracket[0].match.home_score, 11);
  assert.equal((await snapshot(bracket.token)).courts.length, 0);
  assert.equal((await snapshot(standings.token)).standings[0].name, 'Alex Home');
  assert.equal((await snapshot(standings.token)).bracket.length, 0);
  console.log('PASS competition courts, current game scoring, bracket and standings scopes');
  await role('authenticated', manager);
  await assert.rejects(db.query('select delete_venue_display($1,99)', [bracket.id]), /settings changed/);
  await db.query('select delete_venue_display($1,$2)', [bracket.id, bracket.revision]);
  await role('anon');
  assert.deepEqual(await snapshot(bracket.token), { available: false });
  assert.equal((await snapshot(standings.token)).available, true);
  await role('postgres');
  assert.equal(await scalar('select count(*)::integer as value from matches'), 1);
  assert.equal(await scalar('select count(*)::integer as value from match_games'), 2);
  console.log('PASS deleting a display invalidates its link and preserves match/score data');
  console.log('Scoreboard database checks passed. No hosted database accessed.');
} finally { await db.close(); }
