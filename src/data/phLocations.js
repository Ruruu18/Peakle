/** Format a location entry as "City · Region · Country" */
export function formatLocation(loc) {
  if (!loc) return '';
  return `${loc.city} · ${loc.region} · ${loc.country}`;
}

function normalizedLocationText(value) {
  return String(value || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

export function locationMatchesSearch(location, query) {
  const clean = normalizedLocationText(query);
  if (!clean) return true;
  return [location.city, location.region, location.country, ...(location.aliases || [])]
    .some((value) => normalizedLocationText(value).includes(clean));
}

export function findKnownLocation(value) {
  const cityPart = String(value || '').split(/\s*·\s*/)[0];
  const clean = normalizedLocationText(cityPart);
  if (!clean) return null;
  return PH_LOCATIONS.find((location) => (
    normalizedLocationText(location.city) === clean
    || (location.aliases || []).some((alias) => normalizedLocationText(alias) === clean)
  )) || null;
}

export function knownLocationCoordinates(value) {
  const location = findKnownLocation(value);
  return [location?.latitude, location?.longitude].every(Number.isFinite)
    ? { latitude: location.latitude, longitude: location.longitude }
    : null;
}

/** Parse a stored location string back to { city, region, country } or null */
export function parseLocation(str) {
  if (!str) return null;
  const parts = str.split(' · ');
  if (parts.length === 3) {
    const found = findKnownLocation(parts[0]);
    if (found && found.region === parts[1]) return found;
    return { city: parts[0], region: parts[1], country: parts[2] };
  }
  // legacy: just a city name
  const found = findKnownLocation(str);
  return found || { city: str, region: '', country: 'Philippines' };
}
